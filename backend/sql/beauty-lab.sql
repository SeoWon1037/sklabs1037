-- 1. T_INGREDIENT : 화장품 성분 사전 (147개, 직접 정리)
--    - 성분 분석·기획 브리프에서 "AI는 읽기만, 판단은 사전으로" → AI가 성분 효능을 지어내지 않게
--    - FUNCTIONAL   : 식약처 기능성화장품 고시 성분 (미백 / 주름 / 자외선차단 / 여드름 / 탈모)
--    - ALLERGEN_YN  : 식약처 알레르기 유발 가능 착향제 25종
--                     (씻어내는 제품 0.01%, 씻어내지 않는 제품 0.001% 넘게 들어가면 성분명 표시)
--    - CAUTION_SKIN : 주의가 필요한 피부 (민감성 / 건성 / 지성 / 여드름)
--    - ALIASES      : 다른 표기 (쉼표로 구분) → 메칠/메틸, 애씨드/애시드 같은 표기 차이는 서버에서 맞춰서 비교
-- 2. T_BEAUTY_LOG  : 분석·브리프 기록 (하루 사용 횟수 제한, 내 기록)
-- ※ 성분 설명은 일반적인 정보이고, 피부 반응은 사람마다 달라요.
-- ============================================

CREATE TABLE T_INGREDIENT (
     ID             BIGSERIAL       PRIMARY KEY
    ,NAME_KO        VARCHAR(100)    NOT NULL UNIQUE      -- 한글 성분명 (대한화장품협회 표기 기준)
    ,NAME_EN        VARCHAR(200)                         -- INCI 영문명
    ,ALIASES        VARCHAR(500)                         -- 다른 표기 (쉼표 구분)
    ,CATEGORY       VARCHAR(30)     NOT NULL             -- 역할 (보습, 진정, 방부제 ...)
    ,DESCRIPTION    VARCHAR(300)    NOT NULL             -- 쉬운 설명
    ,FUNCTIONAL     VARCHAR(20)                          -- 기능성 고시 성분: 미백 / 주름 / 자외선차단 / 여드름 / 탈모
    ,ALLERGEN_YN    CHAR(1)         NOT NULL DEFAULT 'N' CHECK (ALLERGEN_YN IN ('Y', 'N'))
    ,CAUTION        VARCHAR(300)                         -- 주의할 점
    ,CAUTION_SKIN   VARCHAR(50)                          -- 주의 피부 (쉼표 구분)
    ,INS_DAY        TIMESTAMPTZ     NOT NULL DEFAULT NOW()
);

CREATE TABLE T_BEAUTY_LOG (
     ID             BIGSERIAL       PRIMARY KEY
    ,USER_ID        BIGINT          NOT NULL REFERENCES T_USER (ID)
    ,KIND           VARCHAR(10)     NOT NULL CHECK (KIND IN ('ANALYZE', 'BRIEF'))
    ,INPUT_TYPE     VARCHAR(10)     NOT NULL CHECK (INPUT_TYPE IN ('IMAGE', 'TEXT'))
    ,TITLE          VARCHAR(200)                         -- 제품명 또는 요청 앞부분
    ,ITEM_COUNT     INTEGER                              -- 읽은 성분 수
    ,RESULT_JSON    TEXT            NOT NULL             -- 결과 (다시 보기)
    ,INS_DAY        TIMESTAMPTZ     NOT NULL DEFAULT NOW()
);

-- 내 기록 / 오늘 사용 횟수
CREATE INDEX IX_BEAUTY_LOG_USER ON T_BEAUTY_LOG (USER_ID, INS_DAY DESC);

